#!/usr/bin/env bash
# ==============================================================================
# اسکریپت بروزرسانی خودکار و دیپلوی نسخه جدید ربات کتابخوارشو روی سرور
# نحوه اجرا روی سرور لینوکس:
# chmod +x docker/deploy.sh
# ./docker/deploy.sh
# ==============================================================================

set -e

echo "=================================================="
echo "🚀 1. دریافت آخرین تغییرات و کدهای جدید از گیت‌هاب..."
echo "=================================================="
git pull origin main

echo ""
echo "=================================================="
echo "📦 2. دریافت آخرین ایمیج آماده داکر و راه‌اندازی نسخه جدید..."
echo "=================================================="
docker compose pull
docker compose up -d --remove-orphans

echo ""
echo "=================================================="
echo "🧹 3. پاکسازی ایمیج‌های موقت و بدون استفاده..."
echo "=================================================="
docker image prune -f

echo ""
echo "=================================================="
sleep 5
if ! docker compose ps --status running | grep -q "ketabkharsho_bot"; then
  echo "❌ کانتینر ربات در حال اجرا نیست؛ لاگ‌های اخیر:"
  docker compose logs --tail=100 ketabkharsho-bot
  exit 1
fi

echo "✅ نسخه جدید ربات با موفقیت فعال و اجرا شد!"
echo "=================================================="
docker compose ps
