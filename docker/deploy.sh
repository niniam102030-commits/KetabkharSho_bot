#!/usr/bin/env bash
# ==============================================================================
# اسکریپت بروزرسانی خودکار و دیپلوی نسخه جدید ربات کتابخوارشو روی سرور
# نحوه اجرا روی سرور لینوکس:
# chmod +x docker/deploy.sh
# ./docker/deploy.sh
