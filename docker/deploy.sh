set -e

echo "=================================================="
echo "🚀 1. دریافت آخرین تغییرات و کدهای جدید از گیت‌هاب..."
echo "=================================================="
git pull origin main

echo ""
echo "=================================================="
echo "📦 2. بیلد مجدد کانتینر داکر و راه‌اندازی نسخه جدید..."
echo "=================================================="
docker compose up -d --build

echo ""
echo "=================================================="
echo "🧹 3. پاکسازی ایمیج‌های موقت و بدون استفاده..."
echo "=================================================="
docker image prune -f

echo ""
echo "=================================================="
echo "✅ نسخه جدید ربات با موفقیت فعال و اجرا شد!"
echo "=================================================="
docker compose ps
